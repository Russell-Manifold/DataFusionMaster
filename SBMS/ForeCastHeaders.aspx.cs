       protected void lbtnCreateNew_Click(object sender, EventArgs e)
        {
            ForCastHeader FCHead = new ForCastHeader();
            FCHead.CompanyID = CurrentUser.CoID;
            FCHead.Status = "NEW";
            FCHead.Active = true;
            FCHead.DocDate = DateTime.Now;
              using (SBMSEntities _db = new SBMSEntities(Config.GetConnectionString()))
            {
                _db.ForCastHeaders.Add(FCHead);
                _db.SaveChanges();
                int newfcid = FCHead.ID;

                ForCastLine FcL = new ForCastLine();
                FcL.CompanyID = CurrentUser.CoID;
                FcL.DocID = newfcid;
                FcL.Active = true;
                _db.ForCastLines.Add(FcL);
                _db.SaveChanges();
                Response.Redirect("~/ForeCastDetailed.aspx?fcid=" + newfcid, false);
            }
        }

        protected void lbtnDelete_Click(object sender, EventArgs e)
        {
            LinkButton lbtnFC = (LinkButton)sender;
            GridViewRow row = (GridViewRow)lbtnFC.NamingContainer;
            int fcid = Convert.ToInt32(lbtnFC.CommandArgument);
            using (SBMSEntities _db = new SBMSEntities(Config.GetConnectionString()))
            {
                var fcHead = _db.ForCastHeaders.Where(x => x.CompanyID == CurrentUser.CoID && x.ID == fcid).ToList();
                _db.ForCastHeaders.RemoveRange(fcHead);

                var fcLines = _db.ForCastLines.Where(x => x.CompanyID == CurrentUser.CoID && x.DocID == fcid).ToList();
                _db.ForCastLines.RemoveRange(fcLines);

                _db.SaveChanges();
                LoadFCs();
                ShowMessage(sender, EventArgs.Empty, "Successfully Deleted");
            }

         }

        protected void ShowMessage(object sender, EventArgs e, string msg)
        {
            string message = "alert('" + msg + "')";
            ScriptManager.RegisterClientScriptBlock((sender as Control), this.GetType(), "alert", message, true);
        }

